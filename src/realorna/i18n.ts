export type CopyKey = keyof typeof en;

const DICT: Record<Lang, Record<CopyKey, string>> = { en, id };

export function translate(lang: Lang, key: CopyKey, params?: Record<string, string | number>) {
  let s: string = DICT[lang][key] ?? DICT.en[key] ?? key;
  if (params) {
    for (const n in params) s = s.split("{" + n + "}").join(String(params[n]));
  }
  return s;
}
